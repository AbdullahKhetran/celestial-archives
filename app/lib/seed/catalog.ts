const imaged = ["nssdca-impacts", "lroc-2016"];

function lrocPin(
  latitudeDeg: number,
  longitudeDeg: number,
  elevationM: number,
  uncertaintyM: number,
  sourceIds: string[],
  extras?: Partial<LocationInput>,
): LocationInput {
  return {
    latitudeDeg,
    longitudeDeg,
    elevationM,
    uncertaintyM,
    referenceFrame: DE421,
    method: "lroc_imaged",
    specificity: "object",
    isPreferred: true,
    sourceIds,
    ...extras,
  };
}

function impactHardware(input: {
  id: string;
  missionId: string;
  name: string;
  typeId?: string;
  summary: string;
  summarySourceIds?: string[];
  latitudeDeg: number;
  longitudeDeg: number;
  elevationM?: number;
  uncertaintyM?: number;
  method?: LocationMethod;
  occurredOn: string;
  regionName?: string;
  note?: string;
  extraLocations?: LocationInput[];
  restingState?: HardwareInput["restingState"];
  eventType?: "impact" | "landing";
}): HardwareInput {
  const sourceIds = input.summarySourceIds ?? imaged;
  const hasLroc = input.elevationM !== undefined && input.uncertaintyM !== undefined;
  const eventType = input.eventType ?? "impact";
  return {
    id: input.id,
    missionId: input.missionId,
    typeId: input.typeId ?? "impactor",
    name: input.name,
    restingState: input.restingState ?? "impacted",
    condition: "inactive",
    summary: input.summary,
    summarySourceIds: sourceIds,
    locations: [
      {
        latitudeDeg: input.latitudeDeg,
        longitudeDeg: input.longitudeDeg,
        elevationM: input.elevationM,
        uncertaintyM: input.uncertaintyM,
        referenceFrame: DE421,
        method: input.method ?? (hasLroc ? "lroc_imaged" : "literature"),
        specificity: "object",
        isPreferred: true,
        regionName: input.regionName,
        note: input.note,
        sourceIds,
      },
      ...(input.extraLocations ?? []),
    ],
    events: [
      {
        id: `${input.id}-${eventType}`,
        eventType,
        occurredOn: input.occurredOn,
        precision: "day",
        title: eventType === "landing" ? "Soft-landed" : "Struck the Moon",
        summary: input.summary,
        placesOnSurface: true,
        sourceIds,
      },
    ],
  };
}

function siteChild(input: {
  id: string;
  missionId: string;
  parentId: string;
  name: string;
  summary: string;
  sourceIds: string[];
  arrivedOn: string;
  typeId?: string;
  condition?: HardwareInput["condition"];
}): HardwareInput {
  return {
    id: input.id,
    missionId: input.missionId,
    parentId: input.parentId,
    typeId: input.typeId ?? "instrument",
    name: input.name,
    restingState: "on_surface",
    condition: input.condition ?? "inactive",
    summary: input.summary,
    summarySourceIds: input.sourceIds,
    locations: [
      {
        method: "unknown",
        specificity: "site",
        isPreferred: true,
        note: "No separate coordinate is published. The map uses the parent station's pin.",
        sourceIds: input.sourceIds,
      },
    ],
    events: [
      {
        id: `${input.id}-deployment`,
        eventType: "deployment",
        occurredOn: input.arrivedOn,
        precision: "day",
        title: "Deployed with the station",
        summary: `${input.name} was deployed with its station. The date is the day that station was turned on.`,
        placesOnSurface: true,
        sourceIds: input.sourceIds,
      },
    ],
  };
}

